/// Emoji matching `query` (by name or keyword), best first.
pub fn search(query: &str) -> Vec<(&'static Emoji, fuzzy::Match)> {
    let query = query.trim();
    let mut results: Vec<(i32, usize, &'static Emoji, fuzzy::Match)> = EMOJI
        .iter()
        .enumerate()
        .filter_map(|(i, e)| {
            let by_name = fuzzy::score(query, e.name);
            // Keywords count too (an exact keyword strongly), but only name
            // matches get highlighted.
            let by_keyword = e
                .keywords
                .split_whitespace()
                .filter_map(|k| {
                    fuzzy::score(query, k)
                        .map(|m| if k.eq_ignore_ascii_case(query) { m.score + 40 } else { m.score - 15 })
                })
                .max();
            match (by_name, by_keyword) {
                (Some(m), k) => Some((m.score.max(k.unwrap_or(i32::MIN)), i, e, m)),
                (None, Some(k)) => Some((k, i, e, fuzzy::Match { score: k, positions: Vec::new() })),
                (None, None) => None,
            }
        })
        .collect();
    results.sort_by(|a, b| b.0.cmp(&a.0).then(a.1.cmp(&b.1)));
    results.into_iter().map(|(_, _, e, m)| (e, m)).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn finds_by_name_and_keyword() {
        assert_eq!(search("fire")[0].0.glyph, "🔥");
        assert_eq!(search("thumbs up")[0].0.glyph, "👍");
        assert_eq!(search("lol")[0].0.glyph, "😂");
        assert_eq!(search("rocket")[0].0.glyph, "🚀");
    }

    #[test]
    fn empty_query_lists_everything_in_order() {
        let all = search("");
        assert_eq!(all.len(), EMOJI.len());
        assert_eq!(all[0].0.glyph, EMOJI[0].glyph);
    }

    #[test]
    fn names_are_unique_and_lowercase() {
        let mut names: Vec<&str> = EMOJI.iter().map(|e| e.name).collect();
        assert!(names.iter().all(|n| n.to_lowercase() == *n));
        names.sort();
        let before = names.len();
        names.dedup();
        assert_eq!(names.len(), before);
    }
}
